/**
 * Headless balance simulation: bot versus bot in Node, every matchup played twice with sides swapped.
 * Usage: npm run balance -- [pairs=120] [difficulty=normal] [--md report.md]
 */
import fs from 'node:fs';
import { runMatch } from './runmatch';
import { RNG } from '../src/sim/rng';
import { HERO_LIST } from '../src/data/heroes';
import { CARD_LIST } from '../src/data/cards';
import { randomDeck, type Difficulty } from '../src/ai/bot';
import { CONFIG } from '../src/data/config';

const args = process.argv.slice(2);
const pairs = +(args.find(a => /^\d+$/.test(a)) ?? 120);
const diff = (args.find(a => ['easy', 'normal', 'hard'].includes(a)) ?? 'normal') as Difficulty;
const mdIdx = args.indexOf('--md'); const mdPath = mdIdx >= 0 ? args[mdIdx + 1] : '';

const side = [0, 0, 0]; let total = 0, timeSum = 0, sd = 0; const times: number[] = [];
const hero: Record<string, { p: number; w: number; k: number; d: number; lh: number; dmg: number }> = Object.fromEntries(HERO_LIST.map(h => [h.id, { p: 0, w: 0, k: 0, d: 0, lh: 0, dmg: 0 }]));
const card: Record<string, { p: number; w: number; plays: number }> = Object.fromEntries(CARD_LIST.map(c => [c.id, { p: 0, w: 0, plays: 0 }]));
const lv = { s6: 0, n6: 0, s12: 0, n12: 0 };
const eco = { lvl: 0, gold: 0, lh: 0, dn: 0, kills: 0, cards: 0, camps: 0, boss: 0, runes: 0, waste: 0, items: 0, n: 0 };
const t0 = Date.now();
for (let i = 0; i < pairs; i++) {
  const r = new RNG(1000 + i * 31);
  const hs: [string, string] = [HERO_LIST[i % 6].id, HERO_LIST[(i * 5 + Math.floor(i / 6)) % 6].id];
  const ds: [string[], string[]] = [randomDeck(r), randomDeck(r)];
  for (let swap = 0; swap < 2; swap++) {
    const H: [string, string] = swap ? [hs[1], hs[0]] : hs, D: [string[], string[]] = swap ? [ds[1], ds[0]] : ds;
    const m = runMatch(5000 + i * 2 + swap, H, D, [diff, diff]);
    total++; side[m.winner]++; timeSum += m.time; times.push(m.time); if (m.sim.suddenDeath) sd++;
    for (const t of [0, 1] as const) {
      const won = m.winner === t ? 1 : m.winner === 2 ? 0.5 : 0;
      hero[H[t]].p++; hero[H[t]].w += won;
      for (const c of D[t]) { card[c].p++; card[c].w += won; }
      for (const pl of m.sim.teams[t].playLog) card[pl.card].plays++;
      if (m.lvl6[t]) { lv.s6 += m.lvl6[t]; lv.n6++; } if (m.lvl12[t]) { lv.s12 += m.lvl12[t]; lv.n12++; }
      const st = m.sim.teams[t].stats, h = m.sim.heroes[t].hero!;
      { const hh = hero[H[t]]; hh.k += st.heroKills; hh.d += st.deaths; hh.lh += st.lastHits; hh.dmg += st.damageDealt; }
      eco.n++; eco.lvl += h.level; eco.gold += st.goldEarned; eco.lh += st.lastHits; eco.dn += st.denies; eco.kills += st.heroKills; eco.cards += st.cardsPlayed; eco.camps += st.campsCleared; eco.boss += st.bossKills; eco.runes += st.runes; eco.waste += st.essenceWasted; eco.items += h.items.filter(Boolean).length;
    }
  }
}
times.sort((a, b) => a - b);
const pct = (a: number, b: number) => (b ? (a / b * 100).toFixed(1) : '0.0') + '%';
const mmss = (s: number) => `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, '0')}`;
const L: string[] = [];
L.push(`# Balance report`, ``, `${total} matches (${pairs} matchups x 2 with sides swapped), ${diff} bot vs ${diff} bot, random legal decks. Generated by \`npm run balance\` in ${((Date.now() - t0) / 1000).toFixed(0)}s.`, ``);
L.push(`## Sides`, ``, `| Bottom (Frost) wins | Top (Ember) wins | Draws |`, `|---|---|---|`, `| ${side[0]} (${pct(side[0], total)}) | ${side[1]} (${pct(side[1], total)}) | ${side[2]} (${pct(side[2], total)}) |`, ``);
L.push(`## Match length`, ``, `Average ${mmss(timeSum / total)}, median ${mmss(times[times.length >> 1])}, shortest ${mmss(times[0])}, longest ${mmss(times[times.length - 1])}. Regular time is ${mmss(CONFIG.match.duration)}, sudden death adds up to ${mmss(CONFIG.match.suddenDeath)}.`, ``, `Ended by destroying the Ancient before 8:00: ${total - sd} (${pct(total - sd, total)}). Went to sudden death: ${sd} (${pct(sd, total)}).`, ``);
L.push(`## Per-side averages at match end`, ``, `Hero level ${(eco.lvl / eco.n).toFixed(1)}, gold earned ${(eco.gold / eco.n).toFixed(0)}, items held ${(eco.items / eco.n).toFixed(1)}, last hits ${(eco.lh / eco.n).toFixed(0)}, denies ${(eco.dn / eco.n).toFixed(1)}, hero kills ${(eco.kills / eco.n).toFixed(1)}, cards played ${(eco.cards / eco.n).toFixed(0)}, camps cleared ${(eco.camps / eco.n).toFixed(1)}, boss kills ${(eco.boss / eco.n).toFixed(2)}, runes ${(eco.runes / eco.n).toFixed(1)}, essence wasted at cap ${(eco.waste / eco.n).toFixed(1)}.`, ``, `Ultimate (level 6) reached on average at ${mmss(lv.s6 / Math.max(1, lv.n6))}; level 12 reached by ${pct(lv.n12, eco.n)} of heroes, on average at ${mmss(lv.s12 / Math.max(1, lv.n12))}.`, ``);
L.push(`## Heroes`, ``, `| Hero | Picks | Win rate | Kills | Deaths | Last hits | Hero damage |`, `|---|---|---|---|---|---|---|`);
for (const h of HERO_LIST) { const x = hero[h.id], n = Math.max(1, x.p); L.push(`| ${h.name} | ${x.p} | ${pct(x.w, x.p)} | ${(x.k / n).toFixed(1)} | ${(x.d / n).toFixed(1)} | ${(x.lh / n).toFixed(0)} | ${(x.dmg / n / 1000).toFixed(1)}k |`); }
L.push(``, `## Cards`, ``, `Pick = share of decks containing the card. Plays = average times played per match by a deck that has it.`, ``, `| Card | Cost | Pick rate | Win rate | Plays/match |`, `|---|---|---|---|---|`);
for (const c of CARD_LIST.slice().sort((a, b) => card[b.id].w / Math.max(1, card[b.id].p) - card[a.id].w / Math.max(1, card[a.id].p)))
  L.push(`| ${c.name} | ${c.cost} | ${pct(card[c.id].p, total * 2)} | ${pct(card[c.id].w, card[c.id].p)} | ${(card[c.id].plays / Math.max(1, card[c.id].p)).toFixed(1)} |`);
const out = L.join('\n') + '\n';
console.log(out);
if (mdPath) fs.writeFileSync(mdPath, out);
